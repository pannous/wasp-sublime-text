STRING_OR_COMMENT = re.compile(r'"(?:[^"\\]|\\.)*"|//[^\n]*|/\*.*?\*/|\'(?:[^\'\\]|\\.)\'', re.S)
CONST_HEAD = re.compile(r"\b(?:const|static)\s+([A-Z][A-Z0-9_]*)\s*:(?:\[(?:[^\[\]]|\[[^\]]*\])*\]|[^=;])*=")
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.))\'')
IDENTIFIER_PATH = re.compile(r"(?:[a-z_][a-z0-9_]*::)*([A-Z][A-Z0-9_]+)(?:\[(\d+)\])?")


def without_comments(code):
	return STRING_OR_COMMENT.sub(lambda m: "" if m.group(0).startswith("/") else m.group(0), code)


def balanced_end(code, start, closing=";"):
	"""Index of `closing` at bracket depth 0 from start (strings and chars already kept intact)"""
	depth = 0
	position = start
	while position < len(code):
		match = STRING_OR_COMMENT.match(code, position)
		if match:
			position = match.end()
			continue
		char = code[position]
		if char in "([{":
			depth += 1
		elif char in ")]}":
			depth -= 1
			if depth < 0:
				return position
		elif char == closing and depth == 0:
			return position
		position += 1
	raise ValueError(f"unbalanced code from {start}")


def top_level_elements(array_body):
	"""The comma separated elements of `[a, (b, c), …]`"""
	inner = array_body.strip()
	if not inner.startswith("["):
		return [inner]
	elements, depth, current, position = [], 0, "", 1
	while position < len(inner) - 1:
		match = STRING_OR_COMMENT.match(inner, position)
		if match:
			current += match.group(0)
			position = match.end()
			continue
		char = inner[position]
		depth += char in "([{"
		depth -= char in ")]}"
		if char == "," and depth == 0:
			elements.append(current)
			current = ""
		else:
			current += char
		position += 1
	return [element for element in elements + [current] if element.strip()]


class RustSources:
	def __init__(self, warp):
		self.files = {path.relative_to(warp).as_posix(): without_comments(path.read_text())
		              for root in RUST_ROOTS for path in warp.glob(f"{root}/**/*.rs")}
		self.constants = {}  # (file, name) → initializer
		for file, code in self.files.items():
			for head in CONST_HEAD.finditer(code):
				self.constants[(file, head.group(1))] = code[head.end():balanced_end(code, head.end())]

	def initializer(self, file, name):
		if (file, name) in self.constants:
			return self.constants[(file, name)]
		elsewhere = [key for key in self.constants if key[1] == name]
		if len(elsewhere) == 1:
			return self.constants[elsewhere[0]]
		raise KeyError(f"warp has no constant {name} in {file} (found in {[key[0] for key in elsewhere]})")

	def strings(self, expression, file):
		"""String literals of an expression, constants it names resolved (`NAME`, `module::NAME`, `NAME[2]`)"""
		words = []
		position = 0
		while position < len(expression):
			string = STRING.match(expression, position)
			identifier = IDENTIFIER_PATH.match(expression, position)
			if string:
				words.append(string.group(1) if string.group(1) is not None else string.group(2))
				position = string.end()
			elif identifier and (position == 0 or not expression[position - 1].isalnum()):
				words += self.resolved(identifier.group(1), identifier.group(2), file)
				position = identifier.end()
			else:
				position += 1
		return words

	def resolved(self, name, index, file):
		try:
			initializer = self.initializer(file, name)
		except KeyError:
			return []  # an enum variant or a type, not a word
		values = self.strings(initializer, file)
		return values[int(index):int(index) + 1] if index is not None else values

	def constant_words(self, file, name, mode=None):
		initializer = self.initializer(file, name)
		if mode in ("first", "rest"):
			elements = [self.strings(element, file) for element in top_level_elements(initializer)]
			return [word for found in elements for word in (found[:1] if mode == "first" else found[1:])]
		return self.strings(initializer, file)

	def function_words(self, file, function):
		code = self.files[file]
		head = re.search(rf"\bfn\s+{function}\b[^{{]*\{{", code)
		if not head:
			raise KeyError(f"warp has no function {function} in {file}")
		return self.strings(code[head.end():balanced_end(code, head.end(), "}")], file)

	def call_arguments(self, directory, function):
		calls = re.compile(rf"\b{function}\(\s*([A-Za-z_:\"][^()]*)\)")
		return [word for file, code in self.files.items() if file.startswith(directory)
		        for argument in calls.findall(code) for word in self.strings(argument, file)]

	def has_literal(self, word):
		return any(f'"{word}"' in code or f"'{word}'" in code for code in self.files.values())


def source_words(rust, source):
	kind = source[0]
	if kind == "fn":
		return rust.function_words(source[1], source[2])
	if kind == "calls":
		return rust.call_arguments(source[1], source[2])
	if kind == "words":
		missing = [word for word in source[1:] if not rust.has_literal(word)]
		if missing:
			print(f"left out, no literal in warp's sources: {missing}", file=sys.stderr)
		return [word for word in source[1:] if word not in missing]
	return rust.constant_words(*source)


def usage_corpus():
	texts = []
	for folder in USAGE_CORPUS:
		for path in (WARP / folder).rglob("*"):
			if path.suffix in {".rs", ".warp", ".wasp", ".md"} and path.is_file():
				texts.append(path.read_text(errors="ignore"))
	return "\n".join(texts)


def used_as_call(word, corpus):
	return re.search(rf"(?:\.{word}\b|(?<![\w·]){word}\s*\(|(?<![\w·.]){word} +[\w\"'\[(])", corpus) is not None


def is_glyph(token):
	"""An operator or constant written without ASCII: `√`, `⊤`, `ø`, `π`"""
	return bool(token) and not any(char.isascii() for char in token)


def longest_first(found):
	return sorted(found, key=lambda token: (-len(token), token))


def collect_words(rust):
	corpus = usage_corpus()
	taken, words = {}, {}  # word → the scope that has it
	for scope in SCOPE_ORDER:
		tokens = {token for source in SOURCES[scope] for token in source_words(rust, source)}
		free = lambda token: token not in taken or taken[token] in SHARED_WORDS.get(scope, ())
		found = {word for word in tokens if WORD.match(word) and word not in EXCLUDED and free(word)}
		if scope == CALL_CHECKED:
			unused = sorted(word for word in found if not used_as_call(word, corpus))
			print(f"runtime names never called in {USAGE_CORPUS}, left out: {unused}", file=sys.stderr)
			found -= set(unused)
			words[MERGED_INTO] = longest_first(set(words[MERGED_INTO]) | found)
		else:
			words[scope] = longest_first(found)
		taken.update({word: scope for word in found if word not in taken})
		glyphs = {token for token in tokens if is_glyph(token) and free(token)}
		glyph_key = f"{MERGED_INTO if scope == CALL_CHECKED else scope}_glyphs"
		words[glyph_key] = longest_first(set(words.get(glyph_key, [])) | glyphs)
		taken.update({glyph: scope for glyph in glyphs if glyph not in taken})
	return words


def uncolored_keywords(rust, words):
	colored = {word for found in words.values() for word in found}
	return sorted({word for source in P165_LISTS for word in rust.constant_words(*source)} - colored)


def undocumented_keywords(words):
	page = KEYWORD_PAGE.read_text()
	return sorted({word for scope in DOCUMENTED_SCOPES for word in words[scope]
	               if not re.search(rf"(?<![\w]){re.escape(word)}(?![\w])", page)})


def generated_variables(words, syntax):
	"""A variable per word list the syntax names or that has words; an empty one never matches"""
	lines = [BEGIN_MARK, "  # from warp's sources, see SOURCES in scripts/update_words.py; rerun instead of editing"]
	lines += [f"  {scope}: (?:{'|'.join(map(re.escape, found)) or '(?!)'})" for scope, found in words.items()
	          if found or "{{" + scope + "}}" in syntax]
	return lines + [END_MARK]


def rewrite_syntax(words):
	text = SYNTAX.read_text()
	begin, end = text.index(BEGIN_MARK), text.index(END_MARK) + len(END_MARK)
	SYNTAX.write_text(text[:begin] + "\n".join(generated_variables(words, text)) + text[end:])


def write_completions(words):
	completions = [{"trigger": f"{word}\tbuilt-in", "contents": f"{word}($1)"} for word in sorted(words["support_function"])]
	completions += [{"trigger": f"{word}\t{scope.replace('_', ' ')}", "contents": word}
	                for scope in DOCUMENTED_SCOPES + ["storage_type"]
	                for word in sorted(words[scope])]
	rows = ",\n".join("\t\t" + json.dumps(completion, ensure_ascii=False) for completion in completions)
	COMPLETIONS.write_text(f'{{\n\t"scope": "source.warp",\n\t"completions": [\n{rows}\n\t]\n}}\n')


if __name__ == "__main__":
	rust_sources = RustSources(WARP)
	found_words = collect_words(rust_sources)
	rewrite_syntax(found_words)
	write_completions(found_words)
	for scope, found in found_words.items():
		print(f"{scope} ({len(found)}): {' '.join(sorted(found))}")
	problems = {"P165 keywords no scope colors": uncolored_keywords(rust_sources, found_words),
	            f"keywords {KEYWORD_PAGE} does not document": undocumented_keywords(found_words)}
	for problem, found in problems.items():
		if found:
			print(f"error: {problem}: {' '.join(found)}", file=sys.stderr)
	sys.exit(1 if any(problems.values()) else 0)
